import streamlit as st

st.set_page_config(
    page_title="Финансовый мини-ассистент",
    page_icon="💰",
    layout="centered",
)

st.title("💰 Финансовый мини-ассистент")
st.write(
    "Введите данные — приложение покажет условное распределение портфеля "
    "и объяснит, какие правила повлияли на результат."
)
st.caption(
    "Учебная модель на заданных правилах. "
    "Языковая модель и прогнозирование рынка не используются."
)

with st.form("financial_form"):
    age = st.slider("Возраст, лет", 18, 90, 30)

    income = st.number_input(
        "Ежемесячный доход, руб.",
        min_value=0,
        value=100000,
        step=5000,
    )

    expenses = st.number_input(
        "Ежемесячные расходы, руб.",
        min_value=0,
        value=60000,
        step=5000,
    )

    reserve = st.number_input(
        "Размер финансовой подушки, руб.",
        min_value=0,
        value=240000,
        step=10000,
    )

    risk = st.selectbox(
        "Готовность к риску",
        ["Низкая", "Средняя", "Высокая"],
        index=2,
    )

    horizon = st.slider("Горизонт инвестирования, лет", 1, 30, 10)

    submitted = st.form_submit_button("Получить результат")

if submitted:
    st.header("Результат")

    free_money = income - expenses

    st.metric("Остаток дохода после расходов", f"{free_money:,} руб.")

    if expenses > 0:
        reserve_months = reserve / expenses
        st.metric("Подушка покрывает расходы на", f"{reserve_months:.1f} мес.")
    else:
        reserve_months = None
        st.warning(
            "Расходы указаны равными нулю. "
            "Достаточность подушки оценить невозможно."
        )

    if free_money <= 0:
        st.warning(
            "Свободных средств нет: доход не превышает расходы. "
            "По правилам этой учебной модели распределение портфеля "
            "не рассчитывается."
        )

    elif reserve_months is None:
        st.info(
            "Укажите реальные ежемесячные расходы, "
            "чтобы модель могла продолжить расчет."
        )

    elif reserve_months < 3:
        st.warning(
            "Подушка покрывает меньше трех месяцев расходов. "
            "По правилам учебной модели сначала рассматривается "
            "формирование резерва, поэтому портфель не рассчитывается."
        )
        missing = expenses * 3 - reserve
        st.write(
            f"До условного резерва на три месяца не хватает: "
            f"{missing:,} руб."
        )

    else:
        profiles = {
            "Низкая": [80, 15, 5],
            "Средняя": [50, 35, 15],
            "Высокая": [30, 40, 30],
        }

        reliable, balanced, aggressive = profiles[risk]
        reasons = [
            f"Готовность к риску «{risk}» задает исходные доли: "
            f"{reliable}% / {balanced}% / {aggressive}%."
        ]

        if horizon <= 3:
            reliable, balanced, aggressive = 90, 10, 0
            reasons.append(
                "Горизонт не больше трех лет: модель заменяет "
                "исходное распределение на 90% / 10% / 0%. "
                "Это условное жесткое ограничение."
            )

        elif age >= 60:
            transfer = min(10, aggressive)
            reliable += transfer
            aggressive -= transfer
            reasons.append(
                f"Возраст от 60 лет: {transfer} процентных пунктов "
                "перенесены из агрессивной категории в надежную. "
                "Возрастной порог условен и может давать спорные результаты."
            )

        else:
            reasons.append(
                "Дополнительные ограничения по горизонту "
                "и возрасту не сработали."
            )

        shares = [reliable, balanced, aggressive]

        if sum(shares) != 100 or not all(0 <= x <= 100 for x in shares):
            st.error("Ошибка расчета долей. Результат не показывается.")
        else:
            col1, col2, col3 = st.columns(3)
            col1.metric("Надежная", f"{reliable}%")
            col2.metric("Сбалансированная", f"{balanced}%")
            col3.metric("Агрессивная", f"{aggressive}%")

            st.bar_chart(
                {
                    "Доля, %": {
                        "Надежная": reliable,
                        "Сбалансированная": balanced,
                        "Агрессивная": aggressive,
                    }
                }
            )

            st.subheader("Почему получился такой результат")
            for reason in reasons:
                st.write("• " + reason)

            st.caption(
                "Доход и расходы определяют возможность продолжить расчет, "
                "но не меняют доли после прохождения проверки."
            )

with st.expander("Где модель может ошибаться"):
    st.write(
        """
        • Все проценты и пороги заданы для учебной демонстрации,
        а не получены из исследования оптимальных портфелей.

        • Возраст сам по себе не определяет финансовые цели.
        Порог в 60 лет может давать спорный результат.

        • Не учитываются кредиты, иждивенцы, крупные предстоящие
        расходы и уже имеющиеся инвестиции.

        • Три категории условные: конкретные активы не подбираются.
        Название «Надежная» не означает отсутствия риска.

        • Неверно введенные данные приводят к неверным выводам.

        • Приложение не прогнозирует доходность и не гарантирует
        сохранность капитала.
        """
    )

st.info(
    "Учебная демонстрация. Не является индивидуальной инвестиционной "
    "рекомендацией. Расчет основан на заданных правилах, "
    "а не на прогнозе рынка."
)
